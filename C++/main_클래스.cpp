
#include "DArr.h"

// c언어 구조체 vs c++ 클래스, 구조체

// 구조체 
// 사용자가 직접 정의하는 자료형
// - 캡술화(멤버 추가)

// 클래스
// 사용자가 직접 정의하는 자료형
// - 캡슐화(멤버 추가, 멤버 함수)
// - 은닉성(public, private, protected(자식에게만 공개)) 공개범위 설정
// private 으로 설정하면, 외부 공개 및 변경 금지, 
// 자신이 제공하는 멤버 함수를 통해서만 변경 가능
//
// - 상속, 다형성, 추상화

int main()
{
	DArr arr = {};

	// 제공한 전용 함수를 통해서만 내부 멤버가 바뀌어야 한다. 
	Push_Data(&arr, 10);
	Push_Data(&arr, 20);
	Push_Data(&arr, 30);

	// 강제로 멤버값을 막 바꿀 수 없어야 한다.
	arr.MaxCount = 100;

	return 0;
}