


int main()
{
	// 포인터 변수 주소값이 0 ==> 아무것도 가리키지 않은 상태
	// ㄴ 이러한 포인터를 null포인터라고 부름 (포인터 변수 전용)
	int* pInt = nullptr; // = 0; 이랑 똑같음
	char* pChar = nullptr;

	if (pInt == nullptr)
	{
		// 포인터가 비었다
	}
	else
	{
		// 포인터에 뭐가 들어있다. 
	}

	// 포인터 변수는 대상의 주소를 가리키는 역할이기 때문에, 
	// 주소값을 증가하거나 감소할때 다음대상 위치를 알아야 한다. 
	// 따라서 자신이 가리키기로한 대상의 크기만큼 주소값을 이동시킨다. 
	pInt++;
	pChar++;

	// 배열
	// 1. 연속된 메모리 공간에 생성
	// 2. 배열의 이름이 배열의 시작 주소
	int Array[10] = {};

	int* pArr = Array;
	*pArr = 100;
	pArr[0] = 100;

	*(pArr + 1) = 200;
	*(pArr + 2) = 300;

	//*(포인터 + Num) == 포인터[Num]

	return 0;
}