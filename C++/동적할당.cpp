// C언어
#include <cstdlib>


// 포인터와 동적할당

// 스택 영역 - 함수, 지역변수
// 데이터 영역 - 전역, 정적, 

// 위에 변수들은 컴파일 타임에 크기가 고정되어 있음
// ㄴ 프로그램이 실행되면 중도에 변경될 수 없다. 

// 동적할당의 필요성
// 기존의 지역변수나 전역변수는 코드를 작성하는 시점에서 이미 그 크기가 정해지기 때문에
// 이렇게 작성된 코드로 실행된 프로그램은 런타임 중에 
// 메모리를 유동적으로 늘리거나 줄일 수 없게 된다.
// 따라서 프로그램이 실행중일때(런타임) 메모리를 유동적으로 확보하거나 해제 할 수 있는 기능이 필요하다.


int main()
{
	// Mecomry Allocate -> 동적할당, 힙 공간에 메모리 요청함수
	// malloc 함수는 입력된 정수 수치만큼 힙공간에 메모리를 할당해주고,
	// 사용자가 요청한 메모리 공간이 어떤 용도로 쓰일지 알 수 없기 때문
	// 따라서 사용자는 반환된 void* 타입 시작 주소를 자신이 원하는 용도의 포인터로 캐스팅해서 접근한다. 
	char* pData = (char*)malloc(100);
	// malloc은 무슨 용도로 사용할 메모리인지 모르니까 void* 타입으로 반환하고, 컴파일 오류를 막기위해 형변환하여 사용한다.

	// void*에 담긴 주소를 일반 포인터로 옮기는것인 기본적으로 문법오류
	// void* 가 가리키고 있는 곳이 어떤 용도로 사용되고 있었는지 알 수 없기 때문
	void* pVoid = nullptr;
	//char* pChar = pVoid;

	for (int i = 0; i < 100; ++i)
	{
		pData[i] = i + 1;
	}


	// 메모리 해제 필수
	// 런타임도중에 사용할 동적할당 크기를 알 수 없기 때문에 미리 해제하는 코드가 만들어질 수 
	// 동적할당한 메모리의 해제
	free(pData);
	

	return 0;
}