

int main()
{
	// 변수, 상수
	int a = 10;
	// a 가 변수 10이 상수

	// constant, 상수
	// 변수 b를 상수로 취급해달라
	// 처음 초기화 시에만 값을 지정할 수 있음, 이후 부처는 해당 초기화 값으로 본다. 
	const int b = 10; 
	// 지역변수라서 스택에 잡히긴 하는데, 메모리에 접근하는것을 문법 오류로 본다. 

	// 상수지만 형변환까지 해가면서 수정하면 가능함
	// b는 상수화를 걸어둔 변수인거지 진짜 상수는 아님 때문에 메모리도 잡혀있고, 우회하여 수정도 가능하다.
	// 하지만 이렇게까지 우회해서 값을 수정할거면 const로 선언할 필요가 없음.
	int* pInt = (int*) & b; // 포인터 강제 캐스팅을 통해서 b의 값을 변경하려고 시도
	*pInt = 20;

	// 배열 개수는 상수로 지정
	// 배열의 크기에는 상수가(숫자) 들어가야함. 변수는 못들어감 근데 상수 변수는 들어감
	// 변수가 크기로 못들어가는 이유는 컴파일 타임에 함수의 크기를 스택에 올려야하는데, 변수의 값을 중간에 바꾸는 코드는 컴파일러는 알 수 없음 
	// 때문에 값이 바뀔지 모르는 변수는 크기로 지정이 불가능함. 하지만 상수변수는 값을 수정하지 않기로 했기때문에 사용이 가능함.
	int iArr[b] = {};
	// 컴파일 시점에 b는 10으로 취급되기 때문에
	// 사실상 int iArr[10] = {}; 으로 선언한것과 같다

	
	a = 20;


	return 0;
}