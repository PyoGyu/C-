
void main()
{
	// 자료형, 변수

	// 연산자

	// 증감 연산자
	// ++ : 1증가
	// -- : 1감소
	short data = 0;

	data++;
	++data;
	
	// 전위, 후위
	// 타 연산자들과 섞일 경우만 의미가 있

	// 대입 연산자 , 우측값을 왼쪽으로 입력(복사)
	// =
	data = 200;

	short Input = 0;
	Input = data++;
	Input = ++data;

	// 산술 연산자(사칙 연산자) + 나눗셈
	// +, -, *, /  %(모듈러스, 나머지 연산자)

	// 변수명 중복
	// {} 대괄호를 통해서 지역을 선언할 수 있다.
	{
		int Input = 0;

		Input = 0;

		// 상수, 변하지 않는 숫자
		Input = 3 + 10;

		Input = Input + 10;
		Input += 10; // 축약 구문
	}

	//  /(나누기)
	// 정수끼리 나눗셈 -> 몫
	// 실수끼리 나눗셈 -> 나누어 떨어질때까지 나눔, 나머지 X
	{
		int Input = 10 / 3;
		float fInput = 10.f / 3.0f;

		Input = 10 % 3;

		// 나머지 연산자는 실수자료형 데이터에는 사용 불가능(나머지 개념이 없기 때문)
	}

	// 1. 대입 
	// 2. 증감(전위, 후위)
	// 3. 산술(나눗셈, 나머지)

}


