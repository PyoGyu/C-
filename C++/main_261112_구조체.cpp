#pragma pack(1) // 구조체 크기 잡는거 개선하기 위한 키워드. 메모리의 합산 결과로 메모리가 잡힘
// 언리얼에서는 연산 떄문에 사용 못함. 그래서 타입 정렬을 하는게 좋음. 

// 구조체  - 이게 뭐냐? = 프로그래머가 직접 만든 자료형(user Define DataType)
struct MyType
{
	int Arr[10];

	float f;
};

// 구조체는 메모리를 잡을떄 변수중 가장 큰 크기의 타입을 기준으로 메모리를 잡음 
// longlong을 넣을 8 잡고, int 를 넣기 위해 8 잡고, float를 넣을건데 4바이트 남아있으니까 거기 float 넣고, char 넣어야하는데 남는게 없으니까 또 9바이트 잡고 
// ㄴ 전체적으로 총 32바이트의 메모리를 잡고 7바이트가 잉여 메모리
struct MyType1
{
	long long l;
	int		i; // 멤버 변수
	float	f; 
	char	c; 
};

// 만약 구조체 안에 변수가 char, int, short 이렇게 세개가 들어있으면 12바이트를 잡음 
// 왜 8바이트가 아니냐? = char 1을 넣고 3바이트가 남지만 3바이트 안에 int가 안들어가기 때문에 새로 4바이트 할당 받고 3바이트는 빈채로 놨둠.


void main()
{
	MyType1 t = {};

	// sizeof - 바이트단위로 크기정보를 반환
	// 구조체 크기 계산, 가장큰 맴버 기준으로 메모리를 확장한다. 
	// 나열된 멤버를 순차적으로 배치한다.  
	int size = sizeof(MyType1);

	// 구조체 변수에 . 붙여서 세부 멤버를 지칭할 수 있다. 
	t.i = 10;
	t.f = 5.f;
	t.c = 1;

	MyType a = { {1, 2}, 2.1f }; // 첫 번쨰 중괄호는 구조체 초기화, 두번째 중괄호는 구조체 속 배열 초기화 
	a.Arr[0] = 1;
	a.Arr[1] = 2;

}

