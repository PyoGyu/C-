
// 지역(스택), 전역, 정적, 외부(데이터)

// 외부변수(extern)
// 메모리 영역 - 데이터

// extern 키워드는 전역변수를, 다른 파일에서고 쓸 수 있게 해주는 선언이다. 
// 실제 전역변수는 파일 어딘가에 구현되어있어야 함(한번만)
// 해당 전역변수를 다른파일에서 사용하고 싶을 때 extern으로 전방선언해서 사용함.

void Some();

// 선언이지 구현이 안됨. 
// 전방선언 처럼 "이런 변수가 있을거야" 라고 선언하는거임
// 그래서 보통 헤더 파일에 많이 씀
extern int Global;

int main()
{
	Global = 200;

	Some();

	return 0;
}

// 전역변수
int Global = 0;